"""Generate docs/benchmark.md from the task specs and the checker validation run (T2).

    python scripts/build_benchmark_doc.py     (after pulling outputs/runs/t2-validate)

Also writes outputs/runs/t2-validate/summary.json, the committed record of the validation.
"""

import json
from pathlib import Path

from pipeline_agents.bench.families import FAMILIES, TASKS

RUN = Path("outputs/runs/t2-validate")
SOURCES = {
    "bike": ("Bike Sharing", "https://archive.ics.uci.edu/dataset/275/bike+sharing+dataset"),
    "adult": ("Adult", "https://archive.ics.uci.edu/dataset/2/adult"),
    "air": ("Air Quality", "https://archive.ics.uci.edu/dataset/360/air+quality"),
    "bank": ("Bank Marketing", "https://archive.ics.uci.edu/dataset/222/bank+marketing"),
    "diabetes": ("Diabetes 130-US Hospitals", "https://archive.ics.uci.edu/dataset/296"),
    "credit": ("Default of Credit Card Clients", "https://archive.ics.uci.edu/dataset/350"),
    "retail": ("Online Retail", "https://archive.ics.uci.edu/dataset/352/online+retail"),
}


def latest_results() -> dict[tuple[str, str], dict]:
    rows = {}
    for line in (RUN / "results.jsonl").read_text().splitlines():
        row = json.loads(line)
        rows[(row["task"], row["variant"])] = row  # later runs win
    return rows


def main() -> None:
    results = latest_results()
    ok = sum(r["ok"] for r in results.values())
    summary = {
        "solutions": len(results),
        "as_expected": ok,
        "rows": [
            {k: r[k] for k in ("task", "variant", "expected", "got", "holdout_metric", "validation_metric")}
            for r in results.values()
        ],
    }
    (RUN / "summary.json").write_text(json.dumps(summary, indent=2))

    out = [
        "# The benchmark",
        "",
        f"{len(TASKS)} tasks over {len(FAMILIES)} public datasets. Each gives an agent a raw file, a data "
        f"dictionary "
        "and a goal, and checks what it delivers against answers it never sees. This page is generated by "
        "`scripts/build_benchmark_doc.py` from the task specs in `src/pipeline_agents/bench/families/` "
        "and the "
        "checker validation run.",
        "",
        "## How a task is checked",
        "",
        "The agent must deliver `output/pipeline.py`. The checker copies the data and the agent's `.py` "
        "files to a "
        "fresh directory and re-runs the pipeline, so nothing made by hand counts. Then, stage by stage:",
        "",
        "| stage | passes when |",
        "|---|---|",
        "| `clean_rerun` | `pipeline.py` runs from a clean copy |",
        "| `predict` | `predict.py` runs on the hidden holdout, whose columns are only what is known at "
        "prediction "
        "time |",
        "| `coverage` | every holdout row gets a prediction |",
        "| `score` | the holdout metric beats the task threshold |",
        "| `honest_estimate` | the agent's own validation estimate is close to the holdout metric |",
        "| `answer` | an analytical answer matches the hidden answer, within tolerance |",
        "",
        "Each threshold is set above the obvious baseline a practitioner would try first (for example the "
        "mean for each hour, or one strong column). Every measured model that beats that baseline passes; "
        "models that do not, such as linear models on the bike forecast, fail. The measured numbers are "
        "in the comments of each task spec.",
        "",
        "## Tasks",
        "",
        "Split by dataset: no dataset appears in both dev and test. Within a dataset, a warm-up task "
        "comes before "
        "a follow-up task, and the warm-up never contains the follow-up's hidden answers.",
        "",
        "| task | split | role | kind | difficulty | check |",
        "|---|---|---|---|---|---|",
    ]
    for task in TASKS:
        if task.predictive:
            p = task.predictive
            direction = ">=" if p.metric == "roc_auc" else "<="
            honesty = "off" if p.honesty_tolerance >= 1 else f"{p.honesty_tolerance:g}"
            check = f"{p.metric} {direction} {p.threshold:g}; honesty {honesty}"
        else:
            check = f"answer, tolerance {task.analytical.numeric_tolerance:g}"
        out.append(
            f"| `{task.id}` | {task.split} | {task.role} | {task.kind} | {task.difficulty} | {check} |"
        )

    out += [
        "",
        "## Traps",
        "",
        "Which checker stage catches each trap. *score only* means falling for it lowers the "
        "score but is not guaranteed to fail the task.",
        "",
    ]
    for task in TASKS:
        out.append(f"**`{task.id}`**")
        out.append("")
        for trap in task.traps:
            out.append(f"- `{trap.id}` ({trap.kind}, caught by *{trap.caught_by}*): {trap.description}")
        out.append("")

    out += [
        "## Proof that the checkers work",
        "",
        f"Every task ships solutions in `benchmark/solutions/`: a reference and honest alternatives that "
        f"must pass, "
        f"and broken variants that must fail a named stage. **{ok} of {len(results)} behave as expected.**",
        "",
        "| task | solution | expected | got | holdout | own estimate |",
        "|---|---|---|---|---|---|",
    ]
    for (task_id, variant), r in sorted(results.items()):
        h = "" if r["holdout_metric"] is None else f"{r['holdout_metric']:.4f}"
        v = "" if r["validation_metric"] is None else f"{r['validation_metric']:.4f}"
        mark = "" if r["ok"] else " ✗"
        out.append(f"| `{task_id}` | {variant} | {r['expected']} | {r['got']}{mark} | {h} | {v} |")

    out += [
        "",
        "## Known limits",
        "",
        "- **`air-2-co-estimate` does not check honesty.** Honest time-based estimates missed the "
        "holdout by 36-57% "
        "(the validation months are more polluted than the holdout months) while a random split missed "
        "by 28%, so "
        "no tolerance separates them. The random-split solution is kept as `uncaught_random_split`.",
        "- **`diabetes-1-readmit` cannot catch the patient group leak.** Row- and patient-level "
        "cross-validation "
        "differ by 0.003 AUC, because patients average 1.42 encounters.",
        "- **`bank-1-subscribe` uses a random holdout.** The rows are time-ordered and the subscription "
        "rate climbs "
        "from 3% to 46% across the file, so a time-based holdout would mostly measure that shift.",
        "- **The Bank Marketing data contradicts its own README:** 3,311 clients have earlier contacts but "
        '`pdays = 999` ("not previously contacted"), so `bank-2-previous-campaign` only asks unambiguous '
        "questions.",
        "- Thresholds were set from one holdout draw each; margins to the nearest honest and broken "
        "solutions are "
        "in the spec comments.",
        "",
        "## Data",
        "",
        "All datasets are from the UCI Machine Learning Repository under CC BY 4.0. "
        "`scripts/fetch_datasets.py` "
        "downloads them and records a checksum of each archive.",
        "",
    ]
    for family, (name, url) in SOURCES.items():
        out.append(f"- `{family}`: [{name}]({url})")
    out.append("")
    Path("docs/benchmark.md").write_text("\n".join(out))
    print(f"wrote docs/benchmark.md ({ok}/{len(results)} solutions as expected)")


if __name__ == "__main__":
    main()
